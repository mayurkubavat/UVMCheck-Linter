//! Tokens as written, for the duplication rules: a macro call is its name,
//! not its expansion.

use std::collections::HashMap;

use dv_model::{Design, Loc};

use sv_lexer::Kind;

use sv_syntax::{NodeId, Origin};




use crate::syntax::Cst;




/// A token as written: its text, and whether it is an identifier.
pub(crate) type NormToken = (String, bool);

/// Expanded from a macro body (not a macro argument written at the call).
/// slang gives the literal of a `__FILE__ or `__LINE__ in a body a
/// location of its own, outside the expansion.
pub(crate) fn from_macro_body(c: &Cst, t: &sv_syntax::Token) -> bool {
    !t.from_arg && in_define(c, t)
}

/// Written in a define body (or made by an expansion), not in the text a
/// macro was used in: slang's fully original location is not the use's.
pub(crate) fn in_define(c: &Cst, t: &sv_syntax::Token) -> bool {
    if !t.from_macro || (t.written.file == t.origin.file && t.written.offset > t.origin.offset) {
        return false;
    }
    let src = c.tree.sources.get(t.written.file as usize).map(|s| &s[t.written.offset as usize..]).unwrap_or("");
    !(src.starts_with("`__FILE__") || src.starts_with("`__LINE__"))
}

pub(crate) fn macro_name_at(c: &Cst, site: Origin) -> String {
    c.tree.macro_uses.iter().find(|u| u.origin == site).map(|u| u.name.to_string()).unwrap_or_default()
}

/// The tokens of a node as written; code from a macro body is the macro's
/// name, once per expansion.
pub(crate) fn written_tokens(c: &Cst, n: NodeId, out: &mut Vec<NormToken>) {
    let mut last: Option<Origin> = None;
    for t in c.tree.token_range(n) {
        let tok = &c.tree.tokens[t as usize];
        if tok.text.is_empty() {
            continue;
        }
        if from_macro_body(c, tok) {
            if last != Some(tok.origin) {
                out.push((format!("`{}", macro_name_at(c, tok.origin)), false));
                last = Some(tok.origin);
            }
            continue;
        }
        last = None;
        let text = tok.text.to_string();
        out.push(match tok.kind {
            Kind::Identifier => (text, true),
            Kind::EscapedIdentifier => (text.trim_start_matches('\\').to_string(), true),
            // slang lexes the digits after a base as an identifier unless
            // they start with a digit.
            Kind::VectorDigits if !text.starts_with(|ch: char| ch.is_ascii_digit()) => (text, true),
            Kind::IntegerLiteral
            | Kind::IntegerBase
            | Kind::VectorDigits
            | Kind::UnbasedUnsizedLiteral
            | Kind::RealLiteral
            | Kind::TimeLiteral
            | Kind::StringLiteral => (format!("#{text}"), false),
            _ => (text, false),
        });
    }
}

/// The tokens joined; with `rename`, identifiers (apart from called names)
/// become `$1`, `$2`, ... in order of appearance and literals `#`.
pub(crate) fn token_key(toks: &[NormToken], rename: bool) -> String {
    let mut key = String::new();
    let mut ids: HashMap<&str, usize> = HashMap::new();
    for (i, (text, ident)) in toks.iter().enumerate() {
        if !key.is_empty() {
            key.push(' ');
        }
        let called = toks.get(i + 1).is_some_and(|n| n.0 == "(");
        if rename && *ident && !called {
            let n = ids.len() + 1;
            let id = *ids.entry(text.as_str()).or_insert(n);
            key.push('$');
            key.push_str(&id.to_string());
        } else if rename && text.starts_with('#') {
            key.push('#');
        } else {
            key.push_str(text);
        }
    }
    key
}

/// The file's leading comment block says it is generated.
pub(crate) fn is_generated(src: &str) -> bool {
    let mut letters = String::new();
    for l in src.split('\n').take(40) {
        let t = l.trim_start_matches([' ', '\t', '\r']);
        if t.is_empty() {
            continue;
        }
        if !(t.starts_with("//") || t.starts_with("/*") || t.starts_with('*')) {
            break;
        }
        letters.extend(l.chars().filter(|c| c.is_ascii_alphabetic()).map(|c| c.to_ascii_lowercase()));
    }
    ["autogenerated", "automaticallygenerated", "donotedit", "donothandedit", "generatedfile"]
        .iter()
        .any(|m| letters.contains(m))
}

/// Generated files of the design, by file number.
pub(crate) struct Generated<'a> {
    pub(crate) d: &'a Design,
    pub(crate) sources: HashMap<String, &'a str>,
    pub(crate) cache: HashMap<u32, bool>,
}

impl<'a> Generated<'a> {
    pub fn new(d: &'a Design, csts: &'a [Cst]) -> Self {
        let mut sources = HashMap::new();
        for c in csts {
            for (p, s) in c.tree.files.iter().zip(&c.tree.sources) {
                sources.entry(p.to_string_lossy().into_owned()).or_insert(&**s);
            }
        }
        Generated { d, sources, cache: HashMap::new() }
    }

    pub fn at(&mut self, l: Loc) -> bool {
        let (d, sources) = (self.d, &self.sources);
        *self.cache.entry(l.file).or_insert_with(|| sources.get(d.file_name(l)).is_some_and(|s| is_generated(s)))
    }

    pub fn at_path(&self, path: &str) -> bool {
        self.sources.get(path).is_some_and(|s| is_generated(s))
    }
}

pub(crate) fn tok_where(c: &Cst, t: u32) -> String {
    let tok = &c.tree.tokens[t as usize];
    let f = c.tree.files[tok.origin.file as usize].to_string_lossy();
    let base = f.rsplit(['/', '\\']).next().unwrap_or(&f).to_string();
    format!("{base}:{}", c.loc(t).line)
}
