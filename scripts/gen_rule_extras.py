#!/usr/bin/env python3
"""
Generates the data behind `uvmcheck --explain RULE`: each rule's tested
example (testdata/rules/<category>/<ID>/bad.sv and good.sv) and the options it
reads (found in the rule sources), as a C++ source file compiled into the
binary. Run by CMake at build time:

    gen_rule_extras.py --repo <source dir> --out <build dir>/RuleExtras.cpp
"""

import argparse
import re
from pathlib import Path

DELIM = "UVMCHKEX"
OPTION_RE = re.compile(
    r'ruleOption(?:Int|Bool|String)?\(\s*(?:"(?P<id>[A-Z0-9][A-Z0-9.\-]+)"|getId\(\))\s*,\s*"(?P<key>[a-z_0-9]+)"\s*,\s*(?P<default>[^)]*?)\s*\)')
ID_RE = re.compile(r'getId\(\)\s*const\s*override\s*\{\s*return\s*"([A-Z0-9.\-]+)"')


def cpp_raw(text: str) -> str:
    # Split anything that would close the raw string early.
    text = text.replace(f'){DELIM}"', f'){DELIM} "')
    return f'R"{DELIM}({text}){DELIM}"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    repo = Path(args.repo)

    examples = {}
    for case in sorted((repo / "testdata" / "rules").glob("*/*")):
        if not case.is_dir():
            continue
        bad, good = case / "bad.sv", case / "good.sv"
        examples[case.name] = (
            f"testdata/rules/{case.parent.name}/{case.name}",
            bad.read_text(errors="replace") if bad.exists() else "",
            good.read_text(errors="replace") if good.exists() else "",
        )

    options = {}
    for src in sorted((repo / "cpp" / "src").rglob("*.cpp")):
        text = src.read_text(errors="replace")
        ids = ID_RE.findall(text)
        for m in OPTION_RE.finditer(text):
            rule = m["id"] or (ids[0] if len(ids) == 1 else None)
            if not rule:
                continue
            default = m["default"].strip()
            entry = (m["key"], default)
            if entry not in options.setdefault(rule, []):
                options[rule].append(entry)

    out = ["// Generated by scripts/gen_rule_extras.py. Do not edit.",
           '#include "uvmcheck/rules/RuleExtras.h"', "", "namespace uvmcheck::rules {", "",
           "const std::vector<RuleExtra>& ruleExtras() {", "    static const std::vector<RuleExtra> extras = {"]
    for rule in sorted(set(examples) | set(options)):
        where, bad, good = examples.get(rule, ("", "", ""))
        opts = ", ".join(f'{{"{k}", {cpp_raw(d)}}}' for k, d in options.get(rule, []))
        out.append(f'        {{"{rule}", "{where}", {cpp_raw(bad)}, {cpp_raw(good)}, {{{opts}}}}},')
    out += ["    };", "    return extras;", "}", "", "} // namespace uvmcheck::rules", ""]
    text = "\n".join(out)
    dest = Path(args.out)
    if not dest.exists() or dest.read_text() != text:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text)


if __name__ == "__main__":
    main()
