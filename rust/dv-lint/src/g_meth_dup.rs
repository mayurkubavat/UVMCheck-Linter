// ---- written tokens (meth::writtenTokens, meth::tokenKey) ----

/// A token as written: its text, and whether it is an identifier.
pub(crate) type NormToken = (String, bool);

/// Expanded from a macro body (not a macro argument written at the call).
/// slang gives the literal of a `__FILE__ or `__LINE__ in a body a
/// location of its own, outside the expansion.
fn from_macro_body(c: &Cst, t: &sv_syntax::Token) -> bool {
    if !t.from_macro || t.from_arg {
        return false;
    }
    let src = c.tree.sources.get(t.written.file as usize).map(|s| &s[t.written.offset as usize..]).unwrap_or("");
    !(src.starts_with("`__FILE__") || src.starts_with("`__LINE__"))
}

fn macro_name_at(c: &Cst, site: Origin) -> String {
    c.tree.macro_uses.iter().find(|u| u.origin == site).map(|u| u.name.to_string()).unwrap_or_default()
}

/// The tokens of a node as written; code from a macro body is the macro's
/// name, once per expansion.
pub(crate) fn written_tokens(c: &Cst, n: NodeId, out: &mut Vec<NormToken>) {
    let mut last: Option<Origin> = None;
    for t in c.tree.token_range(n) {
        let tok = &c.tree.tokens[t as usize];
        if tok.text.is_empty() {
            continue;
        }
        if from_macro_body(c, tok) {
            if last != Some(tok.origin) {
                out.push((format!("`{}", macro_name_at(c, tok.origin)), false));
                last = Some(tok.origin);
            }
            continue;
        }
        last = None;
        let text = tok.text.to_string();
        out.push(match tok.kind {
            Kind::Identifier => (text, true),
            Kind::EscapedIdentifier => (text.trim_start_matches('\\').to_string(), true),
            // slang lexes the digits after a base as an identifier unless
            // they start with a digit.
            Kind::VectorDigits if !text.starts_with(|ch: char| ch.is_ascii_digit()) => (text, true),
            Kind::IntegerLiteral
            | Kind::IntegerBase
            | Kind::VectorDigits
            | Kind::UnbasedUnsizedLiteral
            | Kind::RealLiteral
            | Kind::TimeLiteral
            | Kind::StringLiteral => (format!("#{text}"), false),
            _ => (text, false),
        });
    }
}

/// The tokens joined; with `rename`, identifiers (apart from called names)
/// become `$1`, `$2`, ... in order of appearance and literals `#`.
pub(crate) fn token_key(toks: &[NormToken], rename: bool) -> String {
    let mut key = String::new();
    let mut ids: HashMap<&str, usize> = HashMap::new();
    for (i, (text, ident)) in toks.iter().enumerate() {
        if !key.is_empty() {
            key.push(' ');
        }
        let called = toks.get(i + 1).is_some_and(|n| n.0 == "(");
        if rename && *ident && !called {
            let n = ids.len() + 1;
            let id = *ids.entry(text.as_str()).or_insert(n);
            key.push('$');
            key.push_str(&id.to_string());
        } else if rename && text.starts_with('#') {
            key.push('#');
        } else {
            key.push_str(text);
        }
    }
    key
}

/// The file's leading comment block says it is generated.
pub(crate) fn is_generated(src: &str) -> bool {
    let mut letters = String::new();
    for l in src.split('\n').take(40) {
        let t = l.trim_start_matches([' ', '\t', '\r']);
        if t.is_empty() {
            continue;
        }
        if !(t.starts_with("//") || t.starts_with("/*") || t.starts_with('*')) {
            break;
        }
        letters.extend(l.chars().filter(|c| c.is_ascii_alphabetic()).map(|c| c.to_ascii_lowercase()));
    }
    ["autogenerated", "automaticallygenerated", "donotedit", "donothandedit", "generatedfile"]
        .iter()
        .any(|m| letters.contains(m))
}

/// Generated files of the design, by file number.
pub(crate) struct Generated<'a> {
    d: &'a Design,
    sources: HashMap<String, &'a str>,
    cache: HashMap<u32, bool>,
}

impl<'a> Generated<'a> {
    pub fn new(d: &'a Design, csts: &'a [Cst]) -> Self {
        let mut sources = HashMap::new();
        for c in csts {
            for (p, s) in c.tree.files.iter().zip(&c.tree.sources) {
                sources.entry(p.to_string_lossy().into_owned()).or_insert(&**s);
            }
        }
        Generated { d, sources, cache: HashMap::new() }
    }

    pub fn at(&mut self, l: Loc) -> bool {
        let (d, sources) = (self.d, &self.sources);
        *self.cache.entry(l.file).or_insert_with(|| sources.get(d.file_name(l)).is_some_and(|s| is_generated(s)))
    }

    pub fn at_path(&self, path: &str) -> bool {
        self.sources.get(path).is_some_and(|s| is_generated(s))
    }
}

/// `file:line` of where a node starts (where its macro was used), as the
/// C++ `where()` prints it.
pub(crate) fn node_where(c: &Cst, n: NodeId) -> String {
    c.first_tok(n).map(|t| tok_where(c, t)).unwrap_or_default()
}

pub(crate) fn tok_where(c: &Cst, t: u32) -> String {
    let tok = &c.tree.tokens[t as usize];
    let f = c.tree.files[tok.origin.file as usize].to_string_lossy();
    let base = f.rsplit(['/', '\\']).next().unwrap_or(&f).to_string();
    format!("{base}:{}", c.loc(t).line)
}

// ---- SV-DUP-002 ----

struct Stmt {
    toks: Vec<NormToken>,
    at: String,
    /// token_key of this statement alone, with renaming.
    shape: String,
    loc: Loc,
}

struct StmtList {
    routine: usize,
    stmts: Vec<Stmt>,
    whole_body: bool,
}

/// A user routine's name as the C++ prints it: `class::name` for methods.
fn routine_name(c: &Cst, n: NodeId) -> String {
    let name = c.tree.child(n, Name).map(|x| c.tree.bare_text(x)).unwrap_or_default();
    let mut p = c.parent(n);
    while let Some(x) = p {
        if c.kind(x) == ClassDecl {
            let k = c.tree.child(x, Name).map(|y| c.tree.bare_text(y)).unwrap_or_default();
            return format!("{k}::{name}");
        }
        p = c.parent(x);
    }
    name
}

/// The statement lists (two or more statements) of a routine body, as
/// slang's StatementList: a body or block's statements.
fn statement_lists(c: &Cst, routine: usize, body: NodeId, home: u32, out: &mut Vec<StmtList>) {
    for n in c.subtree(body) {
        if !matches!(c.kind(n), Body | SeqBlock | ParBlock) {
            continue;
        }
        let mut items: Vec<NodeId> = Vec::new();
        for x in c.items(n) {
            // slang's VariableDeclStatements carry no syntax, so the rule
            // skips declarations.
            if c.kind(x) != DataDecl && is_stmt(c, x) {
                items.push(x);
            }
        }
        // A list that a macro expanded to was written once, in the macro.
        let written_here = items.iter().any(|&x| {
            c.first_tok(x).is_some_and(|t| {
                let tok = &c.tree.tokens[t as usize];
                let w = if from_macro_body(c, tok) { tok.written } else { tok.origin };
                w.file == home
            })
        });
        if !written_here {
            continue;
        }
        let whole_body = n == body || (c.parent(n) == Some(body) && c.items(body).len() == 1 && c.kind(n) == SeqBlock);
        let mut l = StmtList { routine, stmts: Vec::new(), whole_body };
        for x in items {
            let mut toks = Vec::new();
            written_tokens(c, x, &mut toks);
            if toks.is_empty() {
                continue;
            }
            let shape = token_key(&toks, true);
            l.stmts.push(Stmt { toks, shape, at: node_where(c, x), loc: c.loc_of(x) });
        }
        if l.stmts.len() >= 2 {
            out.push(l);
        }
    }
}

fn window_tokens(l: &StmtList, first: usize, last: usize) -> Vec<NormToken> {
    l.stmts[first..=last].iter().flat_map(|s| s.toks.iter().cloned()).collect()
}

fn window_key(l: &StmtList, first: usize, last: usize, rename: bool) -> String {
    token_key(&window_tokens(l, first, last), rename)
}

/// The window repeats a short cycle of statement shapes, like an unrolled
/// loop: it matches itself shifted by one cycle.
fn periodic(l: &StmtList, first: usize, last: usize) -> bool {
    let len = last - first + 1;
    (1..=len / 2).any(|p| (first..).take_while(|k| k + p <= last).all(|k| l.stmts[k].shape == l.stmts[k + p].shape))
}

#[derive(Clone, Copy, PartialEq)]
struct Window {
    list: usize,
    first: usize,
    last: usize,
}

fn clone_fragments(d: &Design, csts: &[Cst], out: &mut Sink) {
    const MIN_TOKENS: usize = 50;
    const MIN_STMTS: usize = 3;
    let generated = Generated::new(d, csts);
    let mut names: Vec<String> = Vec::new();
    let mut lists: Vec<StmtList> = Vec::new();
    let mut seen = HashSet::new();
    for c in csts {
        for n in c.nodes_of(&[FunctionDecl, TaskDecl]) {
            let Some(body) = c.tree.child(n, Body) else { continue };
            let Some((_, nt)) = c.tree.child(n, Name).and_then(|x| c.tree.token_bounds(x)) else { continue };
            let tok = &c.tree.tokens[nt as usize];
            if tok.from_macro {
                continue;
            }
            let path = c.tree.files[tok.origin.file as usize].to_string_lossy().into_owned();
            let base = path.rsplit(['/', '\\']).next().unwrap_or(&path);
            if base.starts_with("uvm_") || generated.at_path(&path) || !seen.insert((path.clone(), tok.origin.offset)) {
                continue;
            }
            names.push(routine_name(c, n));
            statement_lists(c, names.len() - 1, body, tok.origin.file, &mut lists);
        }
    }

    // Smallest window starting at each statement that reaches both minimums.
    let mut by_key: HashMap<String, Vec<Window>> = HashMap::new();
    let mut windows: Vec<(Window, String)> = Vec::new();
    for (li, l) in lists.iter().enumerate() {
        for i in 0..l.stmts.len() {
            let mut tokens = 0;
            let mut j = i;
            while j < l.stmts.len() {
                tokens += l.stmts[j].toks.len();
                if tokens >= MIN_TOKENS && j - i + 1 >= MIN_STMTS {
                    break;
                }
                j += 1;
            }
            if j == l.stmts.len() {
                break;
            }
            if periodic(l, i, j) {
                continue;
            }
            let key = window_key(l, i, j, true);
            let w = Window { list: li, first: i, last: j };
            by_key.entry(key.clone()).or_default().push(w);
            windows.push((w, key));
        }
    }

    let overlaps = |a: &Window, b: &Window| {
        lists[a.list].routine == lists[b.list].routine && a.list == b.list && !(a.last < b.first || b.last < a.first)
    };
    let mut reported: HashSet<(usize, usize)> = HashSet::new();
    let mut covered_until: HashMap<usize, usize> = HashMap::new();
    for (w, key) in &windows {
        if covered_until.get(&w.list).is_some_and(|&u| w.first <= u) {
            continue;
        }
        let mut orig = None;
        for o in &by_key[key] {
            if o.list == w.list && o.first == w.first {
                break; // only earlier occurrences
            }
            if !overlaps(o, w) {
                orig = Some(*o);
                break;
            }
        }
        let Some(orig) = orig else { continue };
        let (lo, lw) = (&lists[orig.list], &lists[w.list]);
        let pair = (lo.routine, lw.routine);
        if reported.contains(&pair) {
            continue;
        }
        // Grow the match while both sides go on the same way.
        let (mut a, mut b) = (orig, *w);
        while a.last + 1 < lo.stmts.len()
            && b.last + 1 < lw.stmts.len()
            && !(a.list == b.list && a.last + 1 >= b.first)
            && window_key(lo, a.first, a.last + 1, true) == window_key(lw, b.first, b.last + 1, true)
        {
            a.last += 1;
            b.last += 1;
        }
        let whole = lo.whole_body
            && lw.whole_body
            && a.first == 0
            && b.first == 0
            && a.last + 1 == lo.stmts.len()
            && b.last + 1 == lw.stmts.len();
        if whole && window_key(lo, a.first, a.last, false) == window_key(lw, b.first, b.last, false) {
            continue;
        }
        reported.insert(pair);
        covered_until.insert(b.list, b.last);
        let tokens = window_tokens(lw, b.first, b.last).len();
        out.add(
            "SV-DUP-002",
            "CloneFragments",
            Severity::Warning,
            format!(
                "{} statements ({tokens} tokens) in '{}' repeat code in '{}' ({}), apart from names and literals. A fix in one copy will \
be missed in the other; move the shared steps into a helper routine or a common base class.",
                b.last - b.first + 1,
                names[lw.routine],
                names[lo.routine],
                lo.stmts[a.first].at
            ),
            lw.stmts[b.first].loc,
        );
    }
}

// ---- SV-DUP-003 ----

fn duplicated_constraint(d: &Design, csts: &[Cst], out: &mut Sink) {
    const MIN_TOKENS: usize = 8;
    let ix = Index::new(csts);
    let mut generated = Generated::new(d, csts);
    let mut seen: HashMap<String, Vec<(&Class, String, String)>> = HashMap::new();
    for cls in user_classes(d) {
        if generated.at(cls.loc) {
            continue;
        }
        let Some((c, decl)) = ix.decl(cls.loc) else { continue };
        if c.kind(decl) != ClassDecl {
            continue;
        }
        for x in c.items(decl) {
            if c.kind(x) != ConstraintDecl {
                continue;
            }
            let Some(blk) = c.tree.child(x, ConstraintBlock) else { continue };
            let Some((_, nt)) = c.tree.child(x, Name).and_then(|n| c.tree.token_bounds(n)) else { continue };
            let name = c.text_of(nt).to_string();
            let loc = c.loc(nt);
            let at = tok_where(c, nt);
            let mut toks = Vec::new();
            written_tokens(c, blk, &mut toks);
            if toks.len() < MIN_TOKENS + 2 {
                continue;
            }
            let firsts = seen.entry(token_key(&toks, false)).or_default();
            let found = firsts
                .iter()
                .find(|(k, ..)| k.id != cls.id && !derives(d, cls.id, k.id) && !derives(d, k.id, cls.id));
            match found {
                Some((k, kname, kat)) => {
                    out.add(
                        "SV-DUP-003",
                        "DuplicatedConstraint",
                        Severity::Warning,
                        format!(
                            "Constraint '{name}' in '{}' repeats constraint '{kname}' of '{}' ({}). Declare it once, in a base class both \
extend or in a shared constraint policy, so a change reaches both.",
                            cls.name,
                            k.name, kat
                        ),
                        loc,
                    );
                }
                None => firsts.push((cls, name, at)),
            }
        }
    }
}

// ---- SV-DUP-004 ----

fn args_of(c: &Cst, n: NodeId) -> Vec<NodeId> {
    let Some(al) = c.tree.child(n, ArgList) else { return Vec::new() };
    c.tree.children(al).filter(|&a| c.kind(a) == Arg).collect()
}

/// The argument whose strings are names, not text: config keys, instance
/// names given to create() and new().
fn name_argument(c: &Cst, n: NodeId) -> Option<NodeId> {
    let args = args_of(c, n);
    if c.kind(n) == NewExpr {
        return args.first().copied();
    }
    let callee = c.tree.children(n).next()?;
    if c.kind(callee) != ScopedExpr {
        return None;
    }
    let method = c.last_text(callee);
    let inner = c.tree.children(callee).next()?;
    match method {
        "create" if c.kind(inner) == ScopedExpr && c.last_text(inner) == "type_id" => args.first().copied(),
        "set" | "get" if c.kind(inner) == NameExpr && c.keyword(inner).is_some_and(|t| c.text_of(t) == "uvm_config_db") => {
            args.get(2).copied()
        }
        _ => None,
    }
}

fn unescape(s: &str) -> String {
    let mut out = String::new();
    let mut it = s.chars();
    while let Some(ch) = it.next() {
        if ch != '\\' {
            out.push(ch);
            continue;
        }
        match it.next() {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some(x) => out.push(x),
            None => {}
        }
    }
    out
}

fn worth_naming(v: &str) -> bool {
    let b = v.as_bytes();
    if b.len() < 4 || b.iter().filter(|c| c.is_ascii_alphabetic()).count() < 3 {
        return false;
    }
    // Pure format strings ("%0d", "%s: %h") say nothing a constant could name.
    let mut stripped = 0;
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'%' {
            while i + 1 < b.len() && !b[i + 1].is_ascii_alphabetic() {
                i += 1;
            }
            i += 2;
            continue;
        }
        if b[i].is_ascii_alphabetic() {
            stripped += 1;
        }
        i += 1;
    }
    stripped >= 3
}

fn repeated_string_literal(d: &Design, csts: &[Cst], out: &mut Sink) {
    const MIN_COUNT: usize = 4;
    let mut generated = Generated::new(d, csts);
    let mut seen = HashSet::new();
    let mut uses: Vec<(String, Loc)> = Vec::new();
    let free = free_routine_names(csts);
    for c in csts {
        // Routine bodies, and module, interface and program items.
        let mut regions: Vec<NodeId> = Vec::new();
        let mut taken: HashSet<NodeId> = HashSet::new();
        for n in c.nodes_of(&[FunctionDecl, TaskDecl, ModuleDecl, InterfaceDecl, ProgramDecl]) {
            let r = if matches!(c.kind(n), FunctionDecl | TaskDecl) {
                let Some(b) = c.tree.child(n, Body) else { continue };
                if bad_body(d, c, b, routine_class(d, c, n), &free) {
                    continue;
                }
                b
            } else {
                n
            };
            // Skip a region inside one already taken (an ancestor of it).
            let inside = std::iter::successors(Some(r), |&x| c.parent(x)).any(|a| taken.contains(&a));
            if !inside {
                taken.insert(r);
                regions.push(r);
            }
        }
        for r in regions {
            let sub = c.subtree(r);
            let mut skip: HashSet<u32> = HashSet::new();
            for &n in &sub {
                if matches!(c.kind(n), CallExpr | NewExpr) {
                    if let Some(a) = name_argument(c, n) {
                        let e = c.tree.children(a).next().map(|e| c.strip(e));
                        if let Some(e) = e.filter(|&e| c.kind(e) == Literal) {
                            skip.extend(c.tree.token_range(e));
                        }
                    }
                }
            }
            let lits = sub.iter().filter(|&&n| c.kind(n) == Literal).filter_map(|&n| c.first_tok(n));
            for t in lits {
                let tok = &c.tree.tokens[t as usize];
                if tok.kind != Kind::StringLiteral || skip.contains(&t) || from_macro_body(c, tok) {
                    continue;
                }
                let w = if tok.from_macro { tok.written } else { tok.origin };
                let path = c.tree.files.get(w.file as usize).map(|p| p.to_string_lossy().into_owned()).unwrap_or_default();
                let base = path.rsplit(['/', '\\']).next().unwrap_or(&path);
                if base.starts_with("uvm_") || !seen.insert((path.clone(), w.offset)) {
                    continue;
                }
                let loc = c.loc_at(w);
                if generated.at(loc) {
                    continue;
                }
                let raw = &tok.text;
                let inner = raw.strip_prefix('"').and_then(|s| s.strip_suffix('"')).unwrap_or(raw);
                uses.push((unescape(inner), loc));
            }
        }
    }
    let class_names: HashSet<&str> = user_classes(d).map(|k| k.name.as_str()).collect();
    let mut by_value: BTreeMap<String, Vec<Loc>> = BTreeMap::new();
    for (v, l) in uses {
        if worth_naming(&v) && !class_names.contains(v.as_str()) {
            by_value.entry(v).or_default().push(l);
        }
    }
    for (value, locs) in by_value {
        if locs.len() < MIN_COUNT {
            continue;
        }
        let files: BTreeSet<&str> = locs.iter().map(|l| d.file_name(*l)).collect();
        out.add(
            "SV-DUP-004",
            "RepeatedStringLiteral",
            Severity::Info,
            format!(
                "The string \"{value}\" is written {} times in {} {}. Declare it once as a localparam string or static const in the \
package, so a change or a typo cannot split the copies.",
                locs.len(),
                files.len(),
                if files.len() == 1 { "file" } else { "files" }
            ),
            locs[0],
        );
    }
}

// ---- SV-DUP-005 ----

/// A class's shape: its role, property count and method bodies with
/// renaming; and how many tokens its methods have.
fn class_shape(d: &Design, ix: &Index, cls: &Class) -> (String, usize) {
    let mut bodies = Vec::new();
    let mut tokens = 0;
    for m in class_methods(cls) {
        let Some((c, n)) = ix.decl(m.loc) else { continue };
        if !matches!(c.kind(n), FunctionDecl | TaskDecl) {
            continue;
        }
        let mut toks = Vec::new();
        written_tokens(c, n, &mut toks);
        tokens += toks.len();
        bodies.push(token_key(&toks, true));
    }
    bodies.sort();
    let mut shape = format!("{}|{}", role_name(role(d, cls)), cls.properties.len());
    for b in bodies {
        shape.push('|');
        shape.push_str(&b);
    }
    (shape, tokens)
}

fn copied_agent_package(d: &Design, csts: &[Cst], out: &mut Sink) {
    const MIN_CLASSES: usize = 3;
    const MIN_PERCENT: usize = 80;
    const MIN_TOKENS: usize = 12;
    let ix = Index::new(csts);
    let mut generated = Generated::new(d, csts);
    // Package name -> (where it is declared, class shapes).
    let mut order: Vec<(String, Loc, String)> = Vec::new();
    let mut shapes: HashMap<String, BTreeMap<String, usize>> = HashMap::new();
    let mut count: HashMap<String, usize> = HashMap::new();
    for cls in user_classes(d) {
        let Some((c, decl)) = ix.decl(cls.loc) else { continue };
        let Some(p) = c.parent(decl).filter(|&p| c.kind(p) == PackageDecl) else { continue };
        if generated.at(cls.loc) {
            continue;
        }
        let Some((_, pt)) = c.tree.child(p, Name).and_then(|n| c.tree.token_bounds(n)) else { continue };
        let pkg = c.text_of(pt).to_string();
        let (shape, tokens) = class_shape(d, &ix, cls);
        if tokens < MIN_TOKENS {
            continue;
        }
        if !count.contains_key(&pkg) {
            order.push((pkg.clone(), c.loc(pt), tok_where(c, pt)));
        }
        *count.entry(pkg.clone()).or_default() += 1;
        *shapes.entry(pkg).or_default().entry(shape).or_default() += 1;
    }
    for i in 0..order.len() {
        for j in 0..i {
            let (a, _, aat) = &order[j];
            let (b, bloc, _) = &order[i];
            let (sa, sb) = (&shapes[a], &shapes[b]);
            let common: usize = sa.iter().map(|(k, n)| (*n).min(sb.get(k).copied().unwrap_or(0))).sum();
            let largest = count[a].max(count[b]);
            if common < MIN_CLASSES || common * 100 < MIN_PERCENT * largest {
                continue;
            }
            out.add(
                "SV-DUP-005",
                "CopiedAgentPackage",
                Severity::Info,
                format!(
                    "Package '{b}' matches '{a}' ({}) in {common} of {largest} classes, apart from names. It looks like a copied agent; \
make one parameterized agent, or a shared base with small subclasses, so a fix lands in both.",
                    aat
                ),
                *bloc,
            );
            break;
        }
    }
}
