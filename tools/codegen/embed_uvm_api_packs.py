#!/usr/bin/env python3
"""Compiles data/uvm-api/*.json into the binary (generated/UvmApiPacks.cpp), read by uvm::ApiPack."""

import argparse
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--packs", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    packs = sorted(Path(args.packs).glob("*.json"))
    lines = ["// Generated by tools/codegen/embed_uvm_api_packs.py from data/uvm-api; do not edit.",
             "#include <cstddef>", "namespace uvmcheck::uvm {",
             "struct EmbeddedPack { const char* version; const char* json; };"]
    for i, p in enumerate(packs):
        text = p.read_text()
        # Split into chunks: some compilers limit the length of one string literal.
        chunks = [text[j:j + 60000] for j in range(0, len(text), 60000)] or [""]
        body = "\n".join(f'R"UVMPACK({c})UVMPACK"' for c in chunks)
        lines.append(f"static const char kPack{i}[] =\n{body};")
    lines.append("extern const EmbeddedPack kEmbeddedUvmApiPacks[] = {")
    for i, p in enumerate(packs):
        lines.append(f'    {{"{p.stem}", kPack{i}}},')
    if not packs:
        lines.append('    {"", ""},')
    lines.append("};")
    lines.append(f"extern const size_t kEmbeddedUvmApiPackCount = {len(packs)};")
    lines.append("} // namespace uvmcheck::uvm")
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    new = "\n".join(lines) + "\n"
    out = Path(args.out)
    if not out.exists() or out.read_text() != new:
        out.write_text(new)


if __name__ == "__main__":
    main()
