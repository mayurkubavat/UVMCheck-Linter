#!/usr/bin/env python3
"""
Generates crates/dv-lint/src/rule_profiles.rs from docs/rules/catalog.json
and the methodology guide (docs/methodology/MG-*.md).

dv-lint selects rules the way uvmcheck does (default selection, --preset,
--experimental); the selection reads each rule's category, profiles,
guidelines and maturity, which the catalog records from the C++ rules
(tools/codegen/gen_rule_docs.py writes it). `--explain` also reads each
rule's severity and sub-rules from the catalog, and the guidelines' levels
and statements from the guide. Rerun this after either changes:

  tools/codegen/gen_rule_profiles.py           rewrite the file
  tools/codegen/gen_rule_profiles.py --check   exit 1 when it is out of date
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CATALOG = REPO / "docs" / "rules" / "catalog.json"
GUIDE = REPO / "docs" / "methodology"
OUT = REPO / "crates" / "dv-lint" / "src" / "rule_profiles.rs"

# Bits as cpp/include/uvmcheck/rules/Rule.h's RuleProfile.
PROFILES = ["soundness", "methodology", "performance", "style", "security", "smells", "advisory"]


def guidelines():
    """(id, level, statement) of each guideline: `## MG-7.1 (Should)` then the bold statement."""
    out = []
    for page in sorted(GUIDE.glob("MG-*.md")):
        for m in re.finditer(r"^## (MG-[\d.]+) \((\w+)\)\n\n\*\*(.+?)\*\*", page.read_text(), re.M | re.S):
            out.append((m[1], m[2], " ".join(m[3].split())))
    return sorted(out, key=lambda g: [int(x) for x in g[0][3:].split(".")])


def render(catalog, guide):
    lines = [
        "// @generated by tools/codegen/gen_rule_profiles.py from docs/rules/catalog.json; do not edit.",
        "//! Each uvmcheck rule's category, profiles (RuleProfile bits), guidelines",
        "//! and maturity, for selecting rules as uvmcheck does, and its description.",
        "",
        "/// (id, category, profile bits, guidelines, experimental)",
        "pub(crate) const RULES: &[(&str, &str, u32, &[&str], bool)] = &[",
    ]
    for r in sorted(catalog["rules"], key=lambda r: r["id"]):
        if r.get("reportedBy"):
            continue  # a sub-rule: selected with the rule that reports it
        bits = 0
        for p in r.get("profiles", []):
            bits |= 1 << PROFILES.index(p)
        guides = ", ".join(json.dumps(g) for g in r.get("guidelines", []))
        exp = "true" if r.get("maturity") == "experimental" else "false"
        lines.append(f'    ({json.dumps(r["id"])}, {json.dumps(r["category"])}, {bits:#x}, &[{guides}], {exp}),')
    lines.append("];")
    lines += ["", "/// (id, name, description) of each rule, for report rule tables.", "pub(crate) const DOCS: &[(&str, &str, &str)] = &["]
    for r in sorted(catalog["rules"], key=lambda r: r["id"]):
        if r.get("reportedBy"):
            continue
        lines.append(f'    ({json.dumps(r["id"])}, {json.dumps(r["name"])}, {json.dumps(r.get("description", ""), ensure_ascii=False)}),')
    lines.append("];")
    lines += [
        "",
        "/// (id, name, category, severity, experimental, reported by, description) of",
        "/// every rule and sub-rule, for `--explain`.",
        "#[allow(clippy::type_complexity)]",
        "pub(crate) const CATALOG: &[(&str, &str, &str, &str, bool, &str, &str)] = &[",
    ]
    for r in sorted(catalog["rules"], key=lambda r: r["id"]):
        exp = "true" if r.get("maturity") == "experimental" else "false"
        fields = [r["id"], r["name"], r["category"], r.get("severity", "WARNING")]
        lines.append("    (" + ", ".join(json.dumps(f) for f in fields) + f", {exp}, {json.dumps(r.get('reportedBy', ''))}, "
                     + json.dumps(r.get("description", ""), ensure_ascii=False) + "),")
    lines.append("];")
    lines += ["", "/// (id, level, statement) of each methodology guideline (docs/methodology).",
              "pub(crate) const GUIDELINES: &[(&str, &str, &str)] = &["]
    for g in guide:
        lines.append("    (" + ", ".join(json.dumps(x, ensure_ascii=False) for x in g) + "),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(json.loads(CATALOG.read_text()), guidelines())
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(REPO)} is out of date; run {Path(__file__).relative_to(REPO)}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
