#!/usr/bin/env python3
"""
Generates crates/dv-lint/src/rule_profiles.rs from docs/rules/catalog.json.

dv-lint selects rules the way uvmcheck does (default selection, --preset,
--experimental); the selection reads each rule's category, profiles,
guidelines and maturity, which the catalog records from the C++ rules
(tools/codegen/gen_rule_docs.py writes it). Rerun this after the catalog
changes:

  tools/codegen/gen_rule_profiles.py           rewrite the file
  tools/codegen/gen_rule_profiles.py --check   exit 1 when it is out of date
"""

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CATALOG = REPO / "docs" / "rules" / "catalog.json"
OUT = REPO / "crates" / "dv-lint" / "src" / "rule_profiles.rs"

# Bits as cpp/include/uvmcheck/rules/Rule.h's RuleProfile.
PROFILES = ["soundness", "methodology", "performance", "style", "security", "smells", "advisory"]


def render(catalog):
    lines = [
        "// @generated by tools/codegen/gen_rule_profiles.py from docs/rules/catalog.json; do not edit.",
        "//! Each uvmcheck rule's category, profiles (RuleProfile bits), guidelines",
        "//! and maturity, for selecting rules as uvmcheck does.",
        "",
        "/// (id, category, profile bits, guidelines, experimental)",
        "pub(crate) const RULES: &[(&str, &str, u32, &[&str], bool)] = &[",
    ]
    for r in sorted(catalog["rules"], key=lambda r: r["id"]):
        if r.get("reportedBy"):
            continue  # a sub-rule: selected with the rule that reports it
        bits = 0
        for p in r.get("profiles", []):
            bits |= 1 << PROFILES.index(p)
        guides = ", ".join(json.dumps(g) for g in r.get("guidelines", []))
        exp = "true" if r.get("maturity") == "experimental" else "false"
        lines.append(f'    ({json.dumps(r["id"])}, {json.dumps(r["category"])}, {bits:#x}, &[{guides}], {exp}),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(json.loads(CATALOG.read_text()))
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(REPO)} is out of date; run {Path(__file__).relative_to(REPO)}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
