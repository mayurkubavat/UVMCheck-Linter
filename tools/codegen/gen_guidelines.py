#!/usr/bin/env python3
"""
Generates crates/dv-lint/src/guidelines.rs from the methodology guide
(docs/methodology/MG-*.md): each guideline's chapter, level and statement,
for `--explain`, `--list-guidelines` and the `reuse` and `guide` presets.
Rerun this after the guide changes:

  tools/codegen/gen_guidelines.py           rewrite the file
  tools/codegen/gen_guidelines.py --check   exit 1 when it is out of date

The rules themselves are not generated: each declares its category,
severity, profiles, guidelines and description where it is registered
(crates/dv-lint/src/rules/<category>/mod.rs), and the catalog is generated
from them (tools/codegen/gen_rule_docs.py).
"""

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
GUIDE = REPO / "docs" / "methodology"
OUT = REPO / "crates" / "dv-lint" / "src" / "guidelines.rs"


def guidelines():
    """(id, chapter title, level, statement): `# MG-7 Title`, `## MG-7.1 (Should)`, the bold statement."""
    out = []
    for page in sorted(GUIDE.glob("MG-*.md")):
        text = page.read_text()
        title = re.search(r"^# MG-\d+ (.+)$", text, re.M)[1].strip()
        for m in re.finditer(r"^## (MG-[\d.]+) \((\w+)\)\n\n\*\*(.+?)\*\*", text, re.M | re.S):
            out.append((m[1], title, m[2], " ".join(m[3].split())))
    return sorted(out, key=lambda g: [int(x) for x in g[0][3:].split(".")])


def render(guide):
    lines = [
        "// @generated by tools/codegen/gen_guidelines.py from docs/methodology; do not edit.",
        "//! The methodology guidelines the rules enforce.",
        "",
        "/// (id, chapter title, level, statement) of each methodology guideline.",
        "pub(crate) const GUIDELINES: &[(&str, &str, &str, &str)] = &[",
    ]
    for g in guide:
        lines.append("    (" + ", ".join(json.dumps(x, ensure_ascii=False) for x in g) + "),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(guidelines())
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(REPO)} is out of date; run {Path(__file__).relative_to(REPO)}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
